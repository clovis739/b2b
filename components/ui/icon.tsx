import {
  Search,
  ChevronRight,
  ChevronDown,
  ArrowRight,
  ArrowLeft,
  ArrowUp,
  ArrowUpRight,
  Globe,
  Heart,
  UserRound,
  LayoutGrid,
  List,
  Check,
  ShieldCheck,
  Leaf,
  Package,
  Ship,
  SlidersHorizontal,
  X,
  Mail,
  CircleHelp,
  Menu,
  MapPin,
  Carrot,
  Sprout,
  Circle,
  Bell,
  MessageSquare,
  FileText,
  Trash2,
  Send,
  Settings,
  CalendarDays,
  Pause,
  Play,
  type LucideIcon,
} from "lucide-react";
const icons: Record<string, LucideIcon> = {
  search: Search,
  chevron: ChevronRight,
  down: ChevronDown,
  arrow: ArrowRight,
  left: ArrowLeft,
  up: ArrowUp,
  external: ArrowUpRight,
  globe: Globe,
  heart: Heart,
  user: UserRound,
  grid: LayoutGrid,
  list: List,
  check: Check,
  shield: ShieldCheck,
  leaf: Leaf,
  box: Package,
  ship: Ship,
  filter: SlidersHorizontal,
  close: X,
  mail: Mail,
  help: CircleHelp,
  menu: Menu,
  location: MapPin,
  carrot: Carrot,
  broccoli: Sprout,
  onion: Sprout,
  potato: Circle,
  tomato: Circle,
  pepper: Sprout,
  bell: Bell,
  message: MessageSquare,
  file: FileText,
  trash: Trash2,
  send: Send,
  settings: Settings,
  calendar: CalendarDays,
  pause: Pause,
  play: Play,
};
export function Icon({
  name,
  size = 20,
  ...props
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const Component = icons[name] || Package;
  return (
    <Component size={size} strokeWidth={1.65} aria-hidden="true" {...props} />
  );
}
